"""Validate Neural-BVI on saved MATLAB TM-mode FDTD GPR records.

The repository includes common-offset records generated by the MATLAB
TM_model2d.m Maxwell FDTD solver. This script treats those records as external
physics observations and scores the Neural-BVI reconstruction against the
corresponding permittivity model after the same normalized resizing used by the
main synthetic experiment.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import asdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import scipy.io as sio
import scipy.ndimage
import torch

from e2e_bvi_gpr import HyperbolaForward, TinyInversionNet, json_safe, run_bvi, set_seed


FDTD_CASES = [
    ("luji_100m", "Rec_luji_100M.mat", "model_luji.mat"),
    ("luji_1_500m", "Rec_luji_1_500M.mat", "model_luji_1.mat"),
    ("luji_10_500m", "Rec_luji_10_500M.mat", "model_luji_10.mat"),
    ("yuan_100m", "Rec_yuan_100M.mat", "model_yuan.mat"),
]


def preprocess_fdtd_bscan(co_data: np.ndarray, n_time: int, n_traces: int) -> tuple[np.ndarray, dict]:
    bscan = np.asarray(co_data, dtype=np.float32)
    bscan = bscan - scipy.ndimage.uniform_filter1d(bscan, size=max(15, bscan.shape[0] // 8), axis=0, mode="nearest")
    bscan = bscan - np.mean(bscan, axis=1, keepdims=True)
    gain = np.sqrt(np.arange(bscan.shape[0], dtype=np.float32) + 1.0)[:, None]
    bscan = bscan * gain
    clip = float(np.percentile(np.abs(bscan), 99.0))
    if clip <= 0:
        clip = 1.0
    bscan = np.clip(bscan / clip, -1.0, 1.0)
    resized = scipy.ndimage.zoom(bscan, (n_time / bscan.shape[0], n_traces / bscan.shape[1]), order=1)
    meta = {
        "input_shape": list(co_data.shape),
        "clip_abs_p99_after_gain": clip,
        "normalized_min": float(resized.min()),
        "normalized_max": float(resized.max()),
    }
    return resized.astype(np.float32), meta


def load_normalized_permittivity(model_path: Path, image_size: int, pos: np.ndarray | None) -> tuple[np.ndarray, dict]:
    mat = sio.loadmat(model_path)
    ep = np.asarray(mat["ep"], dtype=np.float32)
    x = np.asarray(mat["x"], dtype=np.float32).ravel()
    z = np.asarray(mat["z"], dtype=np.float32).ravel()

    x_mask = np.ones_like(x, dtype=bool)
    if pos is not None and pos.size > 1:
        pad = 0.25 * float(np.median(np.diff(np.sort(pos.ravel()))))
        x_mask = (x >= float(pos.min()) - pad) & (x <= float(pos.max()) + pad)
    ep_crop = ep[x_mask, :]

    # MATLAB model matrices are indexed as x,z and plotted as ep'; convert to
    # depth,width for the CNN/FDTD comparison.
    eps_depth_width = ep_crop.T
    clipped_low = float(np.mean(eps_depth_width < 2.0))
    clipped_high = float(np.mean(eps_depth_width > 10.0))
    norm = np.clip((eps_depth_width - 2.0) / 8.0, 0.0, 1.0)
    resized = scipy.ndimage.zoom(
        norm,
        (image_size / norm.shape[0], image_size / norm.shape[1]),
        order=1,
    ).astype(np.float32)
    meta = {
        "ep_shape": list(ep.shape),
        "ep_crop_shape": list(ep_crop.shape),
        "x_range_m": [float(x.min()), float(x.max())],
        "z_range_m": [float(z.min()), float(z.max())],
        "ep_min": float(ep.min()),
        "ep_max": float(ep.max()),
        "clip_fraction_below_2": clipped_low,
        "clip_fraction_above_10": clipped_high,
    }
    return resized, meta


def save_case_figure(
    out_path: Path,
    obs: torch.Tensor,
    truth: torch.Tensor,
    nn_pred: torch.Tensor,
    bvi_mean: torch.Tensor,
    bvi_std: torch.Tensor,
    event_prob: torch.Tensor,
    threshold: float,
    title_prefix: str,
) -> None:
    panels = [
        (obs.squeeze().numpy(), f"{title_prefix} FDTD B-scan", "seismic"),
        (truth.squeeze().numpy(), "FDTD model permittivity", "viridis"),
        (nn_pred.squeeze().numpy(), "E2E CNN", "viridis"),
        (bvi_mean.squeeze().numpy(), "BVI posterior mean", "viridis"),
        (bvi_std.squeeze().numpy(), "BVI posterior std.", "magma"),
        (event_prob.squeeze().numpy(), f"P(m>{threshold:.2f})", "magma"),
    ]
    fig, axes = plt.subplots(2, 3, figsize=(11, 6), constrained_layout=True)
    for ax, (img, title, cmap) in zip(axes.ravel(), panels):
        im = ax.imshow(img, cmap=cmap, aspect="auto")
        ax.set_title(title, fontsize=9)
        ax.set_xticks([])
        ax.set_yticks([])
        fig.colorbar(im, ax=ax, fraction=0.046, pad=0.02)
    fig.savefig(out_path, dpi=220)
    plt.close(fig)


def aggregate_case_metrics(cases: list[dict]) -> dict:
    if not cases:
        return {}
    metric_keys = list(cases[0]["bvi"].keys())
    aggregate: dict[str, float] = {}
    for key in metric_keys:
        vals = []
        for case in cases:
            value = case["bvi"].get(key)
            if value is not None and not (isinstance(value, float) and np.isnan(value)):
                vals.append(float(value))
        if vals:
            arr = np.asarray(vals, dtype=np.float64)
            aggregate[f"{key}_mean"] = float(arr.mean())
            aggregate[f"{key}_std"] = float(arr.std())
    return aggregate


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--simulation-dir", type=Path, default=Path("GPR_simulation"))
    parser.add_argument("--checkpoint", type=Path, default=Path("experiments/bvi_e2e/results_grsl_trust/tiny_inversion_net.pt"))
    parser.add_argument("--out-dir", type=Path, default=Path("experiments/bvi_e2e/fdtd_validation"))
    parser.add_argument("--image-size", type=int, default=48)
    parser.add_argument("--n-time", type=int, default=64)
    parser.add_argument("--n-traces", type=int, default=48)
    parser.add_argument("--latent-dim", type=int, default=12)
    parser.add_argument("--components", type=int, default=3)
    parser.add_argument("--bvi-steps", type=int, default=200)
    parser.add_argument("--samples-per-component", type=int, default=8)
    parser.add_argument("--residual-scale", type=float, default=0.04)
    parser.add_argument("--kl-weight", type=float, default=0.1)
    parser.add_argument("--model-prior-std", type=float, default=0.03)
    parser.add_argument("--noise-std", type=float, default=0.08)
    parser.add_argument("--interrogation-threshold", type=float, default=0.35)
    parser.add_argument("--basis-type", choices=["cosine", "mixed"], default="cosine")
    parser.add_argument("--seed", type=int, default=43)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    set_seed(args.seed)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    net = TinyInversionNet(args.image_size).to(device)
    net.load_state_dict(torch.load(args.checkpoint, map_location=device))
    net.eval()
    forward = HyperbolaForward(args.image_size, args.n_traces, args.n_time).to(device)

    case_summaries = []
    for idx, (case_name, rec_file, model_file) in enumerate(FDTD_CASES, start=1):
        print(f"Running FDTD validation case {idx}/{len(FDTD_CASES)}: {case_name}")
        rec_path = args.simulation_dir / rec_file
        model_path = args.simulation_dir / model_file
        rec = sio.loadmat(rec_path)
        obs_np, obs_meta = preprocess_fdtd_bscan(rec["co_data"], args.n_time, args.n_traces)
        truth_np, model_meta = load_normalized_permittivity(model_path, args.image_size, np.asarray(rec.get("pos", [])))
        obs = torch.tensor(obs_np[None, None], dtype=torch.float32)
        truth = torch.tensor(truth_np[None, None], dtype=torch.float32)

        with torch.no_grad():
            nn_pred = net(obs.to(device)).cpu()

        bvi_result, bvi_mean, bvi_std, event_prob = run_bvi(
            forward=forward,
            observation=obs,
            true_model=truth,
            nn_mean=nn_pred,
            latent_dim=args.latent_dim,
            components=args.components,
            steps=args.bvi_steps,
            samples_per_component=args.samples_per_component,
            residual_scale=args.residual_scale,
            noise_std=args.noise_std,
            kl_weight=args.kl_weight,
            model_prior_std=args.model_prior_std,
            interrogation_threshold=args.interrogation_threshold,
            basis_type=args.basis_type,
            device=device,
        )

        arrays_path = args.out_dir / f"{case_name}_arrays.npz"
        fig_path = args.out_dir / f"{case_name}_result.png"
        np.savez_compressed(
            arrays_path,
            observation=obs.numpy(),
            true_model=truth.numpy(),
            nn_prediction=nn_pred.numpy(),
            bvi_mean=bvi_mean.numpy(),
            bvi_std=bvi_std.numpy(),
            high_eps_probability=event_prob.numpy(),
        )
        save_case_figure(
            fig_path,
            obs,
            truth,
            nn_pred,
            bvi_mean,
            bvi_std,
            event_prob,
            args.interrogation_threshold,
            case_name,
        )
        case_summaries.append(
            {
                "case": case_name,
                "record": str(rec_path),
                "model": str(model_path),
                "record_metadata": {
                    "tout_ns_range": [float(np.min(rec["tout"]) * 1e9), float(np.max(rec["tout"]) * 1e9)],
                    "pos_m_range": [float(np.min(rec["pos"])), float(np.max(rec["pos"]))],
                    **obs_meta,
                },
                "model_metadata": model_meta,
                "bvi": json_safe(asdict(bvi_result)),
                "figure": str(fig_path),
                "arrays": str(arrays_path),
            }
        )

    summary = {
        "config": json_safe(vars(args) | {"device": str(device)}),
        "cases": case_summaries,
        "aggregate": aggregate_case_metrics(case_summaries),
        "notes": (
            "Saved MATLAB TM-mode Maxwell FDTD records are used as external observations. "
            "The inversion network and BVI likelihood were trained with the hyperbola proxy, "
            "so this evaluates out-of-distribution transfer and data-consistency behavior, "
            "not a fully calibrated electromagnetic posterior."
        ),
    }
    summary_path = args.out_dir / "fdtd_validation_summary.json"
    summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(json.dumps(summary["aggregate"], indent=2))
    print(f"saved results to {summary_path}")


if __name__ == "__main__":
    main()
